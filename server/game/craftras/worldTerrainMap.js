function getTerrainType(rows, x, y) {
    const row = rows[y | 0];
    if (!row || x < 0 || x >= 732) return 0;
    let value = row[1] || 0;
    for (let index = 2; index < row.length && x >= row[index]; index += 2) value = row[index + 1];
    return value;
}

